/**
 * Trimmed `GET /openapi/v3/api/v1` schemas (T-0210): Pod (with the PodSpec → Container → ResourceRequirements chain),
 * ConfigMap, Secret and ObjectMeta, in the upstream v3 shape (`allOf` wrappers around `$ref`s, `x-kubernetes-*`
 * extensions). Descriptions are the upstream ones, shortened. Shared schemas are reused by the apps/v1 document.
 */

const ref = (name: string): JSONSchema => ({ $ref: `#/components/schemas/${name}` });
/** A property pointing at another schema, as v3 wraps it: `allOf: [$ref]` with the property's own description. */
const wrapped = (name: string, description: string, extra: JSONSchema = {}): JSONSchema => ({
  allOf: [ref(name)],
  default: {},
  description,
  ...extra,
});
const str = (description: string): JSONSchema => ({ type: 'string', default: '', description });
const stringMap = (description: string): JSONSchema => ({
  type: 'object',
  additionalProperties: { type: 'string', default: '' },
  description,
});

